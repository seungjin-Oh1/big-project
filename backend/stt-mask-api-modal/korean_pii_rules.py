"""한국어 상담 발화에서 개인정보를 잡는 규칙층.

openai/privacy-filter는 영어에는 정확하지만 한국어에서는 자주 뚫린다. 실측:

    "제 이름은 박지연이고 전화번호는 010-1234-5678입니다."  -> 박지연·번호 모두 검출
    "박지연이고요, 1989년생입니다."                          -> 검출 없음
    "최동현이고요, 혼인신고는 2016년 4월 12일에 했습니다."    -> 검출 없음

단서말("제 이름은")이 앞에 있으면 잡고, 조사가 바로 붙으면 놓친다. 그런데 실제
상담에서 이름을 대는 방식은 대부분 뒤쪽이다. 화면은 "개인정보는 자동으로
가려집니다"라고 적어 두고 있어서, 여기가 뚫리면 그 말이 거짓이 된다.

이 파일은 stt-mask-api(8002)에 있던 같은 규칙을 옮겨 온 것이다. 그 서버는
배포에서 빠졌는데 규칙층이 함께 딸려 나가면서, 지금 실제로 도는 경로
(stt-mask-api-modal의 /redact와 실시간 STT)에는 모델 하나만 남아 있었다.

옮기면서 두 군데를 고쳤다 - 아래 NAME_PATTERNS의 세 번째 항목 주석 참고.
"""
from __future__ import annotations

